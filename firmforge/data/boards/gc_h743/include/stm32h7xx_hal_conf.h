/* ==========================================================================
 * GC-H743 板级 HAL 配置
 *
 * 来源：STM32CubeH7 / Projects/NUCLEO-H743ZI/Templates/Inc/stm32h7xx_hal_conf.h
 *       基线副本存于 ~/.firmforge/sources/stm32/cubeh7-templates/（对外部包的
 *       引用，不入库）。本文件除下方标注的改动外与官方模板**逐字节一致**。
 *
 * 与官方模板的唯一差异
 * --------------------
 *   HSE_VALUE  8000000 → 25000000   （本板 X1 = 25 MHz，NUCLEO 是 8 MHz）
 *
 * 刻意保留「53 个 *_MODULE_ENABLED 全部打开」
 * ------------------------------------------
 * 曾计划按板裁剪，评估后**不裁**，三个理由：
 *   1. 这份头文件只决定**包含哪些头**，不决定**编译哪些 .c**。
 *      真正参与编译的模块清单在 `board.yaml::build.hal_modules`，那才是
 *      可控且被测试守着的地方。
 *   2. 裁剪会制造**静默陷阱**：Agent 写 `HAL_ETH_Init` 时，全开状态下得到的是
 *      「链接期 undefined reference: HAL_ETH_Init」——一眼看出"没把 eth 加进
 *      hal_modules"；裁掉之后变成「unknown type name HAL_ETH_HandleTypeDef」，
 *      指向了错误的方向。
 *   3. HAL 模块头之间有隐式依赖（ETH→DMA、SAI→DMA…），逐一验证裁剪后的
 *      最小闭包是额外风险，收益只是省下几百毫秒编译时间。
 *
 * ⚠️ 但 `board.yaml::build.hal_modules` 里的每个模块，其
 *    `HAL_<MOD>_MODULE_ENABLED` 必须在本文件里是打开的 —— 否则会出现
 *    「编译通过、链接缺失」或反过来的「头里有、源没编」。
 *    `tests/test_stm32_provider.py` 守着这条不变式。
 * ========================================================================== */

